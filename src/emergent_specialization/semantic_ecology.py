def parse_action(raw: str | None) -> tuple[str | None, float | None, str | None]:
    if not raw:
        return None, None, "empty"
    try:
        value = json.loads(raw)
    except json.JSONDecodeError:
        return None, None, "malformed"
    if not isinstance(value, dict) or not isinstance(value.get("answer"), str):
        return None, None, "schema"
    answer = value["answer"].strip().upper()
    confidence = value.get("confidence")
    try:
        confidence = float(confidence)
    except (TypeError, ValueError):
        return None, None, "schema"
    if answer not in OUTPUT_CLASSES and answer not in ROOT_CLASSES:
        return None, confidence, "out_of_domain"
    if not 0.0 <= confidence <= 1.0:
        return None, None, "schema"
    return answer, confidence, None


def predictive_identifiability(ecology: Ecology, environment: Environment, family: str, h: int) -> dict[str, Any]:
    train = ecology.training_cases(environment, family, h)
    candidates = ecology.candidate_thetas(family, environment)
    consistent = [theta for theta in candidates if all(ecology.solve_with_theta(theta, family, case.fields) == case.expected for case in train)]
    probes = ecology.probe_cases(environment, family)
    identifiable = [all(ecology.solve_with_theta(theta, family, probe.fields) == ecology.solve_with_theta(consistent[0], family, probe.fields) for theta in consistent) for probe in probes] if consistent else [False] * len(probes)
    return {"h": h, "training_count": len(train), "candidate_count": len(candidates), "consistent_count": len(consistent),
            "probe_count": len(probes), "predictively_identifiable": sum(identifiable) / len(identifiable),
            "oracle_accuracy": sum(ecology.solve(environment, family, p.fields) == p.expected for p in probes) / len(probes)}
